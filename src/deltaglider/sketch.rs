#[cfg(test)]
mod proptests {
    use super::*;
    use proptest::prelude::*;

    proptest! {
        /// Identical data → Hamming distance 0, always.
        #[test]
        fn prop_identical_zero_distance(data in prop::collection::vec(any::<u8>(), 0..50_000)) {
            let s = sketch_hex(&data);
            prop_assert_eq!(hamming_distance_hex(&s, &s), Some(0));
        }

        /// Sketch is always 64 hex chars (256 bits).
        #[test]
        fn prop_sketch_length(data in prop::collection::vec(any::<u8>(), 0..50_000)) {
            let s = sketch_hex(&data);
            prop_assert_eq!(s.len(), 64);
        }

        /// Streaming == one-shot for arbitrary chunk sizes.
        #[test]
        fn prop_streaming_matches_oneshot(
            data in prop::collection::vec(any::<u8>(), 0..50_000),
            chunk_size in 1usize..=4096,
        ) {
            let oneshot = sketch_hex(&data);
            let mut builder = SketchBuilder::new();
            for chunk in data.chunks(chunk_size) {
                builder.update(chunk);
            }
            let streamed = hex::encode(builder.finalize());
            prop_assert_eq!(oneshot, streamed);
        }

        /// Hamming distance is symmetric: d(a,b) == d(b,a).
        #[test]
        fn prop_hamming_symmetric(
            a in prop::collection::vec(any::<u8>(), 1_000..50_000),
            b in prop::collection::vec(any::<u8>(), 1_000..50_000),
        ) {
            let sa = sketch_hex(&a);
            let sb = sketch_hex(&b);
            let d_ab = hamming_distance_hex(&sa, &sb).unwrap();
            let d_ba = hamming_distance_hex(&sb, &sa).unwrap();
            prop_assert_eq!(d_ab, d_ba);
        }

        /// A single byte flip in a large enough file should produce a
        /// small Hamming distance (CDC re-syncs within a few chunks,
        /// and with many chunks the changed votes are a small fraction).
        #[test]
        fn prop_small_change_small_distance(
            base in prop::collection::vec(any::<u8>(), 100_000..200_000),
            flip_pos in 0usize..200_000,
        ) {
            if flip_pos >= base.len() {
                return Ok(());
            }
            let mut modified = base.clone();
            let idx = flip_pos % modified.len();
            modified[idx] ^= 0xFF;
            let s_base = sketch_hex(&base);
            let s_mod = sketch_hex(&modified);
            let dist = hamming_distance_hex(&s_base, &s_mod).unwrap();
            // With ~25 chunks (200KB / 8KB avg), a single byte flip
            // affects ~2-3 chunks. The sign-bit flips are bounded by
            // the fraction of changed votes (~10%).
            prop_assert!(dist <= 80, "single byte flip distance {} > 80", dist);
        }
    }
}
